DEFAULT_ANALYSIS_PROMPT = PER_RUN_DIR / "analysis_prompt.md"

ANALYSIS_STUB_HEADER = """\
<!--
TODO: customize this analysis prompt for the __DISPLAY_NAME__ benchmark.

Seeded by scaffold.py from analysis/per_run/analysis_prompt.md. Review
the tool-name normalisation rules, expected stack names, and any workspace-
specific grading language before running a real analysis pass.
-->

"""


def render_analysis_stub(mapping: dict[str, str]) -> str:
    body = DEFAULT_ANALYSIS_PROMPT.read_text() if DEFAULT_ANALYSIS_PROMPT.exists() else ""
    if not body:
        raise FileNotFoundError(
            f"missing default analysis prompt at {DEFAULT_ANALYSIS_PROMPT}; "
            "scaffold cannot seed a usable template")
    return substitute(ANALYSIS_STUB_HEADER, mapping) + body


# ─────────────────────────────────────────────────────────────
# Rendering
# ─────────────────────────────────────────────────────────────

def substitute(template: str, mapping: dict[str, str]) -> str:
    out = template
    for key, value in mapping.items():
        out = out.replace(key, value)
    return out


def write_file(path: Path, content: str, force: bool) -> None:
    if path.exists() and not force:
        raise FileExistsError(str(path))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    print(f"  + {path.relative_to(REPO_ROOT)}")


# ─────────────────────────────────────────────────────────────
# CLI
# ─────────────────────────────────────────────────────────────

def add_arguments(p: argparse.ArgumentParser) -> None:
    p.add_argument("name", help="Platform slug (lowercase, e.g. discord)")
    p.add_argument("--display-name",
                   help="Human-facing name (default: capitalised slug)")
    p.add_argument("--downstream-token-env",
                   help="Env var the workspace scripts read (default: <NAME>_TOKEN)")
    p.add_argument("--baseline-stack",
                   help="Baseline stack slug (default: same as platform name)")
    p.add_argument("--baseline-display",
                   help="Baseline stack display name (default: '<Display> MCP')")
    p.add_argument("--variant-stack",   default="hintas",
                   help="Variant stack slug (default: hintas)")
    p.add_argument("--variant-display", default="Hintas MCP",
                   help="Variant stack display name (default: 'Hintas MCP')")
    p.add_argument("--force", action="store_true",
                   help="Overwrite existing files")


def run(args: argparse.Namespace) -> int:
    name = args.name.strip().lower()
    if not name.isidentifier() or not name.isascii():
        print(f"ERROR: platform name {name!r} must be a lowercase ASCII identifier",
              file=sys.stderr)
        return 2

    display_name         = args.display_name or name.capitalize()
    downstream_token_env = args.downstream_token_env or f"{name.upper()}_TOKEN"
    baseline_name        = (args.baseline_stack or name).strip().lower()
    baseline_display     = args.baseline_display or f"{display_name} MCP"
    variant_name         = args.variant_stack.strip().lower()
    variant_display      = args.variant_display

    if baseline_name == variant_name:
        print(f"ERROR: baseline and variant stack names must differ "
              f"(both are {baseline_name!r})", file=sys.stderr)
        return 2

    mapping = {
        "__NAME__":                    name,
        "__DISPLAY_NAME__":            display_name,
        "__DOWNSTREAM_TOKEN_ENV__":    downstream_token_env,
        "__BASELINE_NAME__":           baseline_name,
        "__BASELINE_DISPLAY__":        baseline_display,
        "__BASELINE_CONFIG_ENV__":     f"{baseline_name.upper()}_CONFIG_DIR",
        "__BASELINE_CONFIG_DEFAULT__": f"~/.claude-{baseline_name}",
        "__BASELINE_TOKEN_ENV__":      f"{baseline_name.upper()}_TOKEN",
        "__VARIANT_NAME__":            variant_name,
        "__VARIANT_DISPLAY__":         variant_display,
        "__VARIANT_CONFIG_ENV__":      f"{variant_name.upper()}_CONFIG_DIR",
        "__VARIANT_CONFIG_DEFAULT__":  f"~/.claude-{variant_name}",
        "__VARIANT_TOKEN_ENV__":       f"{variant_name.upper()}_TOKEN",
    }

    platform_root = PLATFORMS_DIR / name
    toml_path     = platform_root / f"{name}.toml"
    analysis_path = PER_RUN_DIR / f"{name}_analysis_prompt.md"

    # Refuse to clobber an existing platform unless --force
    collisions = [p for p in (platform_root, toml_path, analysis_path) if p.exists()]
    if collisions and not args.force:
        print("ERROR: refusing to overwrite existing paths (pass --force to override):",
              file=sys.stderr)
        for p in collisions:
            print(f"  - {p.relative_to(REPO_ROOT)}", file=sys.stderr)
        return 3

    print(f"Scaffolding platform {name!r} ({display_name})")
    print(f"  baseline: {baseline_name} ({baseline_display})")
    print(f"  variant:  {variant_name} ({variant_display})")
    print(f"  token env: {downstream_token_env}")
    print()

    # Empty directory structure
    for sub in ("api", "prompts", "scripts", "state"):
        (platform_root / sub).mkdir(parents=True, exist_ok=True)

    # TOML manifest
    write_file(toml_path, substitute(TOML_TEMPLATE, mapping), args.force)

    # Prompts file
    write_file(platform_root / "prompts" / "benchmark_prompts.json",
               json.dumps({"prompts": []}, indent=2) + "\n", args.force)

    # Script stubs
    write_file(platform_root / "scripts" / "reset_workspace.py",
               substitute(RESET_STUB, mapping), args.force)
    write_file(platform_root / "scripts" / "seed_workspace.py",
               substitute(SEED_STUB, mapping), args.force)
    write_file(platform_root / "scripts" / "verify_workspace.py",
               substitute(VERIFY_STUB, mapping), args.force)

    # Analysis prompt — seeded from the default template with a TODO header.
    write_file(analysis_path, render_analysis_stub(mapping), args.force)

    baseline_token_env = mapping["__BASELINE_TOKEN_ENV__"]
    variant_token_env  = mapping["__VARIANT_TOKEN_ENV__"]
    rel_root = platform_root.relative_to(REPO_ROOT)
    print()
    print("Done. Next steps:")
    print(f"  1. Implement the three scripts in {rel_root}/scripts/ (reset, seed, verify).")
    print(f"  2. Populate {rel_root}/prompts/benchmark_prompts.json with benchmark prompts.")
    print("  3. Register the MCP servers inside each stack's CLAUDE_CONFIG_DIR:")
    print(f"     CLAUDE_CONFIG_DIR={mapping['__BASELINE_CONFIG_DEFAULT__']}  (baseline)")
    print(f"     CLAUDE_CONFIG_DIR={mapping['__VARIANT_CONFIG_DEFAULT__']}  (variant)")
    print(f"  4. Drop {downstream_token_env} / {baseline_token_env} / {variant_token_env} "
          f"into {rel_root}/.env (gitignored).")
    print(f"  5. Customise src/benchmarking/analysis/per_run/{name}_analysis_prompt.md "
          f"for this platform.")
    print(f"  6. Smoke-test:  uv run benchmark run --platform {name} "
          f"--stack {baseline_name} --dry-run --skip-setup --prompt-ids 1")
    return 0


def main() -> int:
    p = argparse.ArgumentParser(description="Scaffold a new benchmark platform")
    add_arguments(p)
    return run(p.parse_args())


if __name__ == "__main__":
    sys.exit(main())
